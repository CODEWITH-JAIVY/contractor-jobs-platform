let current: Lang = 'en';
const dict: Record<Lang, Record<Key, string>> = { en, hi };

/** Non-React code (api, native wrappers) ke liye. Components useT() se subscribe karte hain. */
export function tr(key: Key, params?: Params): string {
  let s: string = dict[current][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const serverMsg = (msg: string): string => (current === 'hi' ? srvHi[msg] ?? msg : msg);
export const isKnownServerMsg = (msg: string): boolean => msg in srvHi;
export const monthNames = (): string[] => MONTHS[current];
/** Monday se shuru: index 0 = Mon */
export const weekdayNames = (): string[] => WEEKDAYS[current];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: typeof tr };
const LangCtx = createContext<Ctx>({ lang: 'en', setLang: () => undefined, t: tr });

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');
  const [loaded, setLoaded] = useState(false);

  useEffect(() => {
    SecureStore.getItemAsync('lang')
      .then((v) => {
        if (v === 'hi' || v === 'en') {
          current = v;
          setLangState(v);
        }
      })
      .catch(() => undefined)
      .finally(() => setLoaded(true));
  }, []);

  const setLang = useCallback((l: Lang) => {
    current = l;
    setLangState(l);
    SecureStore.setItemAsync('lang', l).catch(() => undefined);
  }, []);

  const value = useMemo<Ctx>(() => ({ lang, setLang, t: tr }), [lang, setLang]);
  if (!loaded) return null;
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useT = (): Ctx => useContext(LangCtx);
